use serde::Deserialize;
use std::sync::LazyLock;

#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
pub enum ColumnType {
    #[serde(rename = "identity")]
    Identity,
    #[serde(rename = "bigint")]
    BigInt,
    #[serde(rename = "integer")]
    Integer,
    #[serde(rename = "text")]
    Text,
    #[serde(rename = "boolean")]
    Boolean,
    #[serde(rename = "uuid")]
    Uuid,
    #[serde(rename = "timestamp with time zone")]
    Timestamptz,
    #[serde(rename = "jsonb")]
    Jsonb,
    #[serde(rename = "double precision")]
    Double,
}

impl ColumnType {
    pub fn sql(self) -> &'static str {
        match self {
            Self::Identity => "bigint GENERATED BY DEFAULT AS IDENTITY",
            Self::BigInt => "bigint",
            Self::Integer => "integer",
            Self::Text => "text",
            Self::Boolean => "boolean",
            Self::Uuid => "uuid",
            Self::Timestamptz => "timestamp with time zone",
            Self::Jsonb => "jsonb",
            Self::Double => "double precision",
        }
    }

    pub fn postgres_type(self) -> &'static str {
        if self == Self::Identity {
            "bigint"
        } else {
            self.sql()
        }
    }
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Column {
    pub name: String,
    #[serde(rename = "type")]
    pub kind: ColumnType,
    pub nullable: bool,
    pub generated: bool,
    pub expression: Option<String>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Constraint {
    pub name: String,
    pub kind: String,
    pub columns: Option<Vec<String>>,
    pub expression: Option<String>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Index {
    pub name: String,
    pub unique: bool,
    pub columns: Vec<String>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Table {
    pub schema: String,
    pub name: String,
    pub columns: Vec<Column>,
    pub constraints: Vec<Constraint>,
    pub indexes: Vec<Index>,
}

#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub(crate) struct View {
    pub schema: String,
    pub name: String,
    pub definition: String,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Manifest {
    tables: Vec<Table>,
    views: Vec<View>,
}

static MANIFEST: LazyLock<Manifest> = LazyLock::new(|| {
    serde_json::from_str(include_str!("manifest.json")).expect("valid checked-in schema manifest")
});
pub static TABLES: LazyLock<Vec<Table>> = LazyLock::new(|| MANIFEST.tables.clone());
pub(crate) static VIEWS: LazyLock<Vec<View>> = LazyLock::new(|| MANIFEST.views.clone());
