use super::*;
use std::collections::HashSet;

#[test]
fn manifest_covers_real_registers_and_unique_declared_objects() {
    assert_eq!(TABLES.len(), 113);
    assert_eq!(TABLES.iter().map(|t| t.columns.len()).sum::<usize>(), 1395);
    let mut tables = HashSet::new();
    for table in TABLES.iter() {
        assert!(tables.insert((&table.schema, &table.name)));
        let names = table
            .columns
            .iter()
            .map(|c| c.name.as_str())
            .collect::<HashSet<_>>();
        assert_eq!(names.len(), table.columns.len());
        for column in &table.columns {
            assert!(column_ddl(column).is_ok());
        }
        for constraint in &table.constraints {
            assert!(constraint_ddl(constraint).is_ok());
        }
        for index in &table.indexes {
            assert!(index.columns.iter().all(|n| names.contains(n.as_str())));
        }
    }
    for group in ["demo", "live"] {
        for key in crate::models::TABLES[group].as_object().unwrap().keys() {
            assert!(tables.contains(&(&group.to_string(), &key.to_string())));
        }
    }
}

#[test]
fn declaration_quotes_identifiers_and_rejects_ambiguous_generated_defaults() {
    assert_eq!(quote("a\"b"), "\"a\"\"b\"");
    let mut c = Column {
        name: "quoted\"column".into(),
        kind: ColumnType::Identity,
        nullable: false,
        generated: false,
        expression: None,
    };
    assert!(column_ddl(&c)
        .unwrap()
        .contains("GENERATED BY DEFAULT AS IDENTITY"));
    c.expression = Some("7".into());
    assert!(column_ddl(&c).is_err());
    c.kind = ColumnType::Text;
    c.expression = None;
    c.generated = true;
    assert!(column_ddl(&c).is_err());
}
